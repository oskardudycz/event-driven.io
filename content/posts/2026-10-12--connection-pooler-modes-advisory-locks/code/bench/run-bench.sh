#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."

DURATION="${DURATION:-30}"
RESULTS=bench/results.md

trap 'docker compose down -v >/dev/null 2>&1' EXIT
docker compose up -d --wait >/dev/null 2>&1

in_postgres() {
  docker compose exec -T -e PGPASSWORD=app_password postgres sh -c "$1"
}

in_postgres "pgbench -i -q -h localhost -U app_user app" >/dev/null 2>&1

# B1: 50 clients sharing 10 server connections. pgbench's per-transaction
# log (-l) tells how many transactions each client managed to run.
b1() {
  local title=$1 target=$2
  local command="pgbench -S -c 50 -j 4 -T $DURATION -l $target"
  echo "### B1: $title"
  echo
  echo '```'
  echo "$command"
  echo
  in_postgres "rm -rf /tmp/b1 && mkdir /tmp/b1 && cd /tmp/b1 && $command 2>&1 \
    | grep -E 'number of clients|processed|failed|latency average|tps' \
    && cat pgbench_log.* | awk '{ count[\$1]++ } END {
         for (client in count) {
           served++;
           if (count[client] > 1) busy++;
           if (min == \"\" || count[client] < min) min = count[client];
           if (count[client] > max) max = count[client];
         }
         print \"clients that ran at least 1 transaction: \" served;
         print \"clients that ran more than 1 transaction: \" busy;
         print \"transactions per client: min \" min \", max \" max;
       }'"
  echo '```'
  echo
}

# B2: a new connection for each transaction (-C).
b2() {
  local title=$1 target=$2
  local command="pgbench -S -C -c 10 -j 4 -T $DURATION $target"
  echo "### B2: $title"
  echo
  echo '```'
  echo "$command"
  echo
  in_postgres "$command 2>&1 | grep -E 'number of clients|processed|failed|latency average|tps'"
  echo '```'
  echo
}

{
  echo '# Benchmark results'
  echo
  echo "Generated by \`npm run bench\` on $(date -u +%Y-%m-%d). Indicative only: a laptop and Docker, not a tuned production setup."
  echo
  echo '## Environment'
  echo
  echo '```'
  echo "CPU: $(lscpu | sed -n 's/^Model name: *//p')"
  echo "CPU cores: $(nproc)"
  echo "RAM: $(free -h | awk '/^Mem:/ { print $2 }')"
  echo "Docker: $(docker version --format '{{.Server.Version}}')"
  echo "PostgreSQL: $(in_postgres "psql -h localhost -U app_user app -Atc 'SHOW server_version'")"
  echo "PgBouncer: $(docker compose exec -T pgbouncer-session pgbouncer --version | head -1)"
  echo "Duration of each run: ${DURATION}s"
  echo '```'
  echo
  echo '## B1: more clients than server connections'
  echo
  b1 'session mode' '-h pgbouncer-session -p 6432 -U app_user app'
  b1 'transaction mode' '-h pgbouncer-transaction -p 6433 -U app_user app_multiplex'
  echo '## B2: reconnecting for each transaction'
  echo
  b2 'directly to PostgreSQL' '-h localhost -p 5432 -U app_user app'
  b2 'PgBouncer in session mode' '-h pgbouncer-session -p 6432 -U app_user app'
  b2 'PgBouncer in transaction mode' '-h pgbouncer-transaction -p 6433 -U app_user app_multiplex'
} >"$RESULTS"

cat "$RESULTS"
